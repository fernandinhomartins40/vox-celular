import assert from 'node:assert/strict';
import { sendNativePush, readNativePushReceipt } from './nativePushTransport.js';
const now = new Date('2026-10-13T12:00:00Z');
const notice = { id: 'notice', destino: '/pedidos' as const, expiresAt: new Date(now.getTime() + 60000) };
const token = 'ExpoPushToken[fixture_device_token]', access = 'fixture-access-token';
const id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const calls: { url: string; body: Record<string, unknown> }[] = [];
const transport = (body: unknown, status = 200): typeof fetch => (async (url, options) => {
  assert.equal(options?.redirect, 'error'); assert.ok(options?.signal);
  assert.equal((options?.headers as Record<string, string>).Authorization, `Bearer ${access}`);
  calls.push({ url: String(url), body: JSON.parse(String(options?.body)) });
  return new Response(JSON.stringify(body), { status });
}) as typeof fetch;
assert.deepEqual(await sendNativePush(token, notice, access, transport({ data: { status: 'ok', id } }), now), { status: 'queued', ticketId: id });
assert.equal(calls[0].url, 'https://exp.host/--/api/v2/push/send');
assert.equal(calls[0].body.ttl, 60);
assert.deepEqual(calls[0].body.data, { id: 'notice', destino: '/pedidos' });
assert.ok(!JSON.stringify(calls[0].body).includes('pagamento'));
assert.deepEqual(await readNativePushReceipt(id, access, transport({ data: { [id]: { status: 'ok' } } })), { status: 'provider-accepted' });
assert.deepEqual(calls.at(-1)?.body, { ids: [id] });
assert.deepEqual(await readNativePushReceipt(id, access, transport({ data: {} })), { status: 'pending' });
assert.deepEqual(await readNativePushReceipt(id, access, transport({ data: { [id]: { status: 'error', details: { error: 'DeviceNotRegistered' } } } })), { status: 'invalid-subscription' });
assert.deepEqual(await sendNativePush(token, notice, access, transport({ data: { status: 'error', details: { error: 'DeviceNotRegistered' } } }), now), { status: 'invalid-subscription' });
assert.deepEqual(await sendNativePush(token, notice, access, transport({}, 503), now), { status: 'ambiguous' });
assert.deepEqual(await sendNativePush(token, notice, access, transport({}, 401), now), { status: 'rejected' });
assert.deepEqual(await sendNativePush(token, { ...notice, expiresAt: now }, access, transport({}), now), { status: 'expired' });
assert.deepEqual(await sendNativePush(token, notice, access, transport({ data: { status: 'ok' } }), now), { status: 'ambiguous' });
assert.deepEqual(await sendNativePush(token, notice, access, transport({ large: 'x'.repeat(10000) }), now), { status: 'ambiguous' });
await assert.rejects(sendNativePush('https://evil.invalid', notice, access, transport({}), now));
await assert.rejects(sendNativePush(token, { ...notice, destino: '/admin' as never }, access, transport({}), now));
console.log('Native push transport: fixed endpoint, private payload, TTL, queued ticket vs provider receipt, invalid devices and bounded failure handling passed with mocked HTTP.');
