import assert from 'node:assert/strict';
import { accountTokenDigest, accountTokenUsable, issueAccountToken } from './accountToken.js';
const now = Date.now();
const recovery = issueAccountToken('RECUPERAR_SENHA', now);
assert.equal(recovery.token.length, 43);
assert.equal(recovery.digest.length, 64);
assert.notEqual(recovery.token, recovery.digest);
assert.equal(recovery.expiresAt.getTime(), now + 20 * 60000);
assert.equal(accountTokenDigest(recovery.token, 'RECUPERAR_SENHA'), recovery.digest);
assert.notEqual(accountTokenDigest(recovery.token, 'VERIFICAR_EMAIL'), recovery.digest);
assert.notEqual(issueAccountToken('RECUPERAR_SENHA', now).token, recovery.token);
const row = { expiresAt: recovery.expiresAt, consumedAt: null, tokenVersion: 2 };
assert.equal(accountTokenUsable(row, 2, now), true);
assert.equal(accountTokenUsable(row, 3, now), false);
assert.equal(accountTokenUsable(row, 2, recovery.expiresAt.getTime()), false);
assert.equal(accountTokenUsable({ ...row, consumedAt: new Date(now) }, 2, now), false);
assert.equal(accountTokenUsable({ ...row, expiresAt: new Date('invalid') }, 2, now), false);
for (const token of ['', 'x'.repeat(42), 'x'.repeat(44), '/'.repeat(43), 'a'.repeat(42) + '\n']) assert.throws(() => accountTokenDigest(token, 'RECUPERAR_SENHA'));
console.log('Account tokens: cryptographic randomness, purpose separation, short expiry, consumption and credential-version rejection passed.');
