import assert from 'node:assert/strict';
import { accountSmtpSchema, createAccountMailSender } from './accountMailTransport.js';
const config = { host: 'smtp.example.com', port: 587 as const, user: 'fixture', password: 'fixture-only', from: 'vox@example.com', origin: 'https://vox.example.com' };
const token = 'a'.repeat(43);
let release!: () => void;
const gate = new Promise<void>(resolve => { release = resolve; });
let closed = false;
const sender = createAccountMailSender(config, options => {
  assert.equal(options.requireTLS, true);
  assert.equal(options.tls?.rejectUnauthorized, true);
  assert.equal(options.secure, false);
  assert.equal(options.logger, false);
  assert.equal(options.debug, false);
  assert.equal(options.disableFileAccess, true);
  assert.equal(options.disableUrlAccess, true);
  return { async sendMail(message) { assert.equal(message.to, 'client@example.com'); await gate; return { accepted: [message.to], rejected: [] }; }, close() { closed = true; } };
});
const first = sender.send('client@example.com', 'store', token, 'RECUPERAR_SENHA');
const second = sender.send('client@example.com', 'store', token, 'VERIFICAR_EMAIL');
assert.equal((await sender.send('client@example.com', 'store', token, 'RECUPERAR_SENHA')).status, 'unavailable');
release();
assert.equal((await first).status, 'accepted');
assert.equal((await second).status, 'accepted');
assert.equal((await sender.send('bad\r\naddress', 'store', token, 'RECUPERAR_SENHA')).status, 'rejected');
sender.close();
assert.equal(closed, true);
assert.equal((await sender.send('client@example.com', 'store', token, 'RECUPERAR_SENHA')).status, 'unavailable');
const failed = createAccountMailSender(config, () => ({ async sendMail() { throw new Error('private-provider-detail'); }, close() {} }));
assert.deepEqual(await failed.send('client@example.com', 'store', token, 'RECUPERAR_SENHA'), { status: 'failed' });
assert.deepEqual(await failed.send('client@example.com', 'store', token, 'RECUPERAR_SENHA'), { status: 'failed' });
for (const extra of [{ port: 25 }, { origin: 'http://vox.example' }, { from: 'bad' }, { user: 'bad\nuser' }]) assert.equal(accountSmtpSchema.safeParse({ ...config, ...extra }).success, false);
console.log('Account SMTP transport: strict TLS, bounded concurrency, safe errors and close passed with injected sender; no external delivery tested.');
