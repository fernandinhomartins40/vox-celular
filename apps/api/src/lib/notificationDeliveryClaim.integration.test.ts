import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { prisma } from './prisma.js';
import { assertDisposableDatabase } from './disposableDatabase.js';
import { claimNotificationDelivery } from './notificationDeliveryClaim.js';
import { authorizeNotificationDelivery } from './notificationDeliveryAuthorization.js';
import { settleNotificationDelivery } from './notificationDeliverySettlement.js';
import { finalizeNotifications } from './notificationFinalization.js';
import { expireNotifications } from './notificationExpiration.js';
import { reconcileInterruptedDeliveries } from './notificationRecovery.js';
import { claimNativeReceipt, settleNativeReceipt } from './nativePushReceipts.js';

assertDisposableDatabase(process.env.PUSH_DELIVERY_TEST);
const id = `ci-delivery-${randomUUID()}`;
const now = new Date('2026-10-12T12:00:00Z');
try {
  // Prisma stores DateTime as UTC wall time (timestamp without time zone).
  // A non-UTC session catches accidental timestamptz comparisons in raw SQL.
  await prisma.$executeRawUnsafe("ALTER DATABASE voxcelular SET TIME ZONE 'America/Sao_Paulo'");
  await prisma.$disconnect(); // Apply the setting to every connection in the pool.
  await prisma.loja.create({ data: { id, nome: 'Delivery fixture', telefone: '', endereco: '', cidade: '', mapsUrl: '' } });
  await prisma.usuario.create({ data: { id, lojaId: id, nome: 'Fixture', email: `${id}@example.invalid`, senhaHash: 'not-a-login-hash', cliente: { create: { id, lojaId: id, telefone: '', cidade: '', notificacoes: true } } } });
  await prisma.assinaturaPush.create({ data: { id, lojaId: id, clienteId: id, endpointHash: id, credenciais: 'fixture-not-real-credentials' } });
  await prisma.notificacaoCliente.create({ data: { id, lojaId: id, clienteId: id, chaveEvento: id, titulo: 'Fixture', mensagem: 'Fixture', destino: '/pedidos', status: 'PROCESSANDO', expiresAt: new Date('2100-01-01T00:00:00Z') } });
  await prisma.entregaPush.create({ data: { id, notificacaoId: id, assinaturaId: id, proximaTentativaEm: new Date('2000-01-01T00:00:00Z') } });
  await prisma.assinaturaPush.update({ where: { id }, data: { canal: 'EXPO_ANDROID' } });
  assert.notEqual((await claimNotificationDelivery(now))?.id, id, 'Web worker must not claim native devices');
  await prisma.assinaturaPush.update({ where: { id }, data: { canal: 'WEB' } });
  const claims = await Promise.all([claimNotificationDelivery(now), claimNotificationDelivery(now)]);
  assert.equal(claims.filter(row => row?.id === id).length, 1, 'Concurrent claims must not claim a delivery twice');
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).tentativas, 1);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).processandoDesde?.getTime(), now.getTime());
  assert.equal(await reconcileInterruptedDeliveries(new Date(now.getTime() + 9 * 60_000)), 0, 'Live attempts must not be reconciled');
  assert.equal(await reconcileInterruptedDeliveries(new Date(now.getTime() + 10 * 60_000)), 1, 'Interrupted attempts become uncertain');
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'INCERTA');
  assert.equal(await settleNotificationDelivery(id, 1, { status: 'accepted' }, now), false, 'Late settlement must not overwrite an uncertain attempt');
  await finalizeNotifications();
  assert.equal((await prisma.notificacaoCliente.findUniqueOrThrow({ where: { id } })).status, 'INCERTA');
  await prisma.notificacaoCliente.update({ where: { id }, data: { status: 'PROCESSANDO' } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO' } });
  assert.equal((await authorizeNotificationDelivery(id, now))?.id, id);
  await prisma.assinaturaPush.update({ where: { id }, data: { canal: 'EXPO_IOS' } });
  assert.equal(await authorizeNotificationDelivery(id, now), null, 'Web transport authorization must exclude native devices');
  assert.equal((await authorizeNotificationDelivery(id, now, true))?.id, id, 'Configured native delivery must authorize its channel');
  await prisma.assinaturaPush.update({ where: { id }, data: { canal: 'WEB' } });
  await prisma.cliente.update({ where: { id }, data: { notificacoes: false } });
  assert.equal(await authorizeNotificationDelivery(id, now), null, 'Consent revoked after claim must block authorization');
  await prisma.cliente.update({ where: { id }, data: { notificacoes: true } });
  await prisma.assinaturaPush.update({ where: { id }, data: { ativo: false } });
  assert.equal(await authorizeNotificationDelivery(id, now), null, 'Inactive subscription after claim must block authorization');
  await prisma.assinaturaPush.update({ where: { id }, data: { ativo: true } });
  await prisma.notificacaoCliente.update({ where: { id }, data: { expiresAt: now } });
  assert.equal(await authorizeNotificationDelivery(id, now), null, 'Exact expiry must block authorization');
  await prisma.notificacaoCliente.update({ where: { id }, data: { expiresAt: new Date('2100-01-01T00:00:00Z') } });
  await prisma.assinaturaPush.update({ where: { id }, data: { lojaId: 'different-tenant' } });
  assert.equal(await authorizeNotificationDelivery(id, now), null, 'Mismatched subscription tenant must block authorization');
  await prisma.assinaturaPush.update({ where: { id }, data: { lojaId: id } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PENDENTE' } });
  assert.equal(await authorizeNotificationDelivery(id, now), null, 'Unclaimed delivery must not be authorized');
  await prisma.assinaturaPush.update({ where: { id }, data: { ativo: false } });
  assert.notEqual((await claimNotificationDelivery(now))?.id, id, 'Inactive subscription must not be claimed');
  await prisma.assinaturaPush.update({ where: { id }, data: { ativo: true } });
  await prisma.cliente.update({ where: { id }, data: { notificacoes: false } });
  assert.notEqual((await claimNotificationDelivery(now))?.id, id, 'Revoked consent must not be claimed');
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).tentativas, 1);
  await prisma.cliente.update({ where: { id }, data: { notificacoes: true } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO' } });
  assert.equal(await settleNotificationDelivery(id, 2, { status: 'accepted' }, now), false, 'Wrong attempt must not settle');
  assert.equal(await settleNotificationDelivery(id, 1, { status: 'temporary' }, now), true);
  const retry = await prisma.entregaPush.findUniqueOrThrow({ where: { id } });
  assert.equal(retry.status, 'PENDENTE');
  assert.equal(retry.proximaTentativaEm.getTime(), now.getTime() + 60000);
  assert.equal(await settleNotificationDelivery(id, 1, { status: 'accepted' }, now), false, 'Late result must not overwrite a scheduled retry');
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO', tentativas: 2 } });
  assert.equal(await settleNotificationDelivery(id, 2, { status: 'accepted' }, now), true);
  assert.equal(await settleNotificationDelivery(id, 2, { status: 'temporary' }, now), false, 'Duplicate settlement must preserve acceptance');
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'ACEITA');
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO', tentativas: 3, confirmadaEm: null } });
  assert.equal(await settleNotificationDelivery(id, 3, { status: 'invalid-subscription' }, now), true);
  assert.equal((await prisma.assinaturaPush.findUniqueOrThrow({ where: { id } })).ativo, false);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'INVALIDA');
  await prisma.assinaturaPush.update({ where: { id }, data: { ativo: true } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO', tentativas: 4 } });
  await prisma.cliente.update({ where: { id }, data: { notificacoes: false } });
  assert.equal(await settleNotificationDelivery(id, 4, { status: 'accepted' }, now), true);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'CANCELADA');
  assert.equal(await settleNotificationDelivery(id, 4, { status: 'temporary' }, now), false, 'Canceled delivery must never be revived');
  for (const [deliveryStatus, eventStatus] of [['PENDENTE', 'PROCESSANDO'], ['PROCESSANDO', 'PROCESSANDO'], ['unknown-state', 'PROCESSANDO'], ['ACEITA', 'CONCLUIDA'], ['INCERTA', 'INCERTA'], ['INVALIDA', 'FALHA'], ['CANCELADA', 'CANCELADA']] as const) {
    await prisma.notificacaoCliente.update({ where: { id }, data: { status: 'PROCESSANDO' } });
    await prisma.entregaPush.update({ where: { id }, data: { status: deliveryStatus } });
    await finalizeNotifications();
    assert.equal((await prisma.notificacaoCliente.findUniqueOrThrow({ where: { id } })).status, eventStatus);
  }
  await prisma.notificacaoCliente.update({ where: { id }, data: { status: 'CANCELADA' } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'ACEITA' } });
  await finalizeNotifications();
  assert.equal((await prisma.notificacaoCliente.findUniqueOrThrow({ where: { id } })).status, 'CANCELADA', 'Finalization must preserve revoked events');
  await prisma.assinaturaPush.create({ data: { id: `${id}-other`, lojaId: id, clienteId: id, endpointHash: `${id}-other`, credenciais: 'fixture-not-real-credentials' } });
  await prisma.entregaPush.create({ data: { id: `${id}-other`, notificacaoId: id, assinaturaId: `${id}-other`, status: 'FALHA' } });
  await prisma.notificacaoCliente.update({ where: { id }, data: { status: 'PROCESSANDO' } });
  await finalizeNotifications();
  assert.equal((await prisma.notificacaoCliente.findUniqueOrThrow({ where: { id } })).status, 'PARCIAL', 'Mixed acceptance and failure must not claim full success');
  await prisma.notificacaoCliente.createMany({ data: Array.from({ length: 30 }, (_, n) => ({ id: `000-${id}-${n}`, lojaId: id, clienteId: id, chaveEvento: `finalize-${n}`, titulo: 'Fixture', mensagem: 'Fixture', destino: '/pedidos', status: 'PROCESSANDO', expiresAt: new Date('2100-01-01T00:00:00Z') })) });
  assert.equal(await finalizeNotifications(), 25, 'Finalization must respect its batch bound');
  assert.equal(await prisma.notificacaoCliente.count({ where: { lojaId: id, status: 'PROCESSANDO' } }), 5);
  await finalizeNotifications();
  assert.equal(await prisma.notificacaoCliente.count({ where: { lojaId: id, status: 'PROCESSANDO' } }), 0);
  await prisma.notificacaoCliente.createMany({ data: Array.from({ length: 30 }, (_, n) => ({ id: `000-expire-${id}-${n}`, lojaId: id, clienteId: id, chaveEvento: `expire-${n}`, titulo: 'Fixture', mensagem: 'Fixture', destino: '/pedidos', expiresAt: new Date('2000-01-01T00:00:00Z') })) });
  assert.equal(await expireNotifications(now), 25, 'Expiration must respect its batch bound');
  assert.equal(await prisma.notificacaoCliente.count({ where: { lojaId: id, status: 'PENDENTE' } }), 5);
  await expireNotifications(now);
  assert.equal(await prisma.notificacaoCliente.count({ where: { lojaId: id, status: 'PENDENTE' } }), 0);
  await prisma.notificacaoCliente.update({ where: { id }, data: { status: 'PROCESSANDO', expiresAt: now } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO' } });
  await prisma.entregaPush.update({ where: { id: `${id}-other` }, data: { status: 'PENDENTE' } });
  await expireNotifications(now);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'INCERTA');
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id: `${id}-other` } })).status, 'EXPIRADA');
  assert.equal((await prisma.notificacaoCliente.findUniqueOrThrow({ where: { id } })).status, 'INCERTA');
  console.log('Delivery claims, authorization and idempotent settlements passed.');
  await prisma.cliente.update({ where: { id }, data: { notificacoes: true } });
  await prisma.assinaturaPush.update({ where: { id }, data: { ativo: true, canal: 'EXPO_ANDROID' } });
  await prisma.notificacaoCliente.update({ where: { id }, data: { status: 'PROCESSANDO', expiresAt: new Date('2100-01-01T00:00:00Z') } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'PROCESSANDO', tentativas: 1, consultasRecibo: 0 } });
  assert.equal(await settleNotificationDelivery(id, 1, { status: 'queued', ticketId: 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa' }, now), true);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'AGUARDANDO_RECIBO');
  assert.equal(await claimNativeReceipt(now), null, 'Receipt must wait fifteen minutes');
  const due = new Date(now.getTime() + 15 * 60_000);
  const receiptClaims = await Promise.all([claimNativeReceipt(due), claimNativeReceipt(due)]);
  assert.equal(receiptClaims.filter(row => row?.id === id).length, 1, 'Concurrent receipt passes must not claim twice');
  assert.equal(await settleNativeReceipt(id, 2, { status: 'provider-accepted' }, due), false);
  assert.equal(await settleNativeReceipt(id, 1, { status: 'provider-accepted' }, due), true);
  assert.equal(await settleNativeReceipt(id, 1, { status: 'pending' }, due), false, 'Late pending response must not overwrite acceptance');
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'ACEITA');
  await prisma.entregaPush.update({ where: { id }, data: { status: 'AGUARDANDO_RECIBO', consultasRecibo: 2 } });
  await prisma.cliente.update({ where: { id }, data: { notificacoes: false } });
  assert.equal(await settleNativeReceipt(id, 2, { status: 'provider-accepted' }, due), true);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'CANCELADA');
  await prisma.cliente.update({ where: { id }, data: { notificacoes: true } });
  await prisma.entregaPush.update({ where: { id }, data: { status: 'AGUARDANDO_RECIBO', consultasRecibo: 3 } });
  assert.equal(await settleNativeReceipt(id, 3, { status: 'invalid-subscription' }, due), true);
  assert.equal((await prisma.assinaturaPush.findUniqueOrThrow({ where: { id } })).ativo, false);
  await prisma.entregaPush.update({ where: { id }, data: { status: 'AGUARDANDO_RECIBO', consultasRecibo: 5, proximaTentativaEm: now } });
  await claimNativeReceipt(due);
  assert.equal((await prisma.entregaPush.findUniqueOrThrow({ where: { id } })).status, 'INCERTA', 'Abandoned final receipt lookup must become uncertain without resend');
  console.log('Native receipt timing, concurrent claims, consent revocation, invalid device and abandoned lookup passed.');
} finally {
  await prisma.notificacaoCliente.deleteMany({ where: { lojaId: id } });
  await prisma.assinaturaPush.deleteMany({ where: { lojaId: id } });
  await prisma.cliente.deleteMany({ where: { id } });
  await prisma.usuario.deleteMany({ where: { id } });
  await prisma.loja.deleteMany({ where: { id } });
  await prisma.$disconnect();
}
